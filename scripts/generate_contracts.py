"""Generate the HTTP schema and TypeScript request models from the actual server."""

from pathlib import Path
import json
from xverse_studio.api.app import create_app

root = Path(__file__).resolve().parents[1]
spec = create_app(root / ".studio-local/contract-generation").openapi()
out = root / "packages/contracts"
out.mkdir(parents=True, exist_ok=True)
(out / "openapi.json").write_text(
    json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
)


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    for key, separator in [("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")]:
        if key in schema:
            return "(" + separator.join(ts(s) for s in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + ts(schema.get("items", {})) + ">"
    if kind == "object":
        props = schema.get("properties", {})
        if props:
            return (
                "{ "
                + "; ".join(
                    json.dumps(k)
                    + ("" if k in schema.get("required", []) else "?")
                    + ": "
                    + ts(v)
                    for k, v in props.items()
                )
                + " }"
            )
        additional = schema.get("additionalProperties", True)
        return (
            "Record<string, "
            + (ts(additional) if isinstance(additional, dict) else "unknown")
            + ">"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


text = '// Generated by scripts/generate_contracts.py. Do not edit.\nexport const studioApiVersion = "1.0" as const;\n'
for name, schema in spec.get("components", {}).get("schemas", {}).items():
    text += "export type " + name + " = " + ts(schema) + ";\n"
(out / "api.ts").write_text(text, encoding="utf-8")
print("Generated OpenAPI and TypeScript request contracts from server schemas.")
